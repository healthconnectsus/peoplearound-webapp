-- Peoplearound — 0082 a project you can put on a flyer
--
-- Events could leave the app (0074); projects could not. Yet the thing a
-- founder wants to tape to a lamppost is often the project itself — "we are
-- fixing up the Oak Street lot, come help" — before any event exists. So a
-- project can now be published the same way: a share code, and /p/<code>
-- becomes a page anyone can open, the thing a QR code points at.
--
-- And a flyer. One per project, written by the assistant from what the
-- project already says and corrected by its steward, with the code on it.
-- Stored, so it is written once and reused, and every edit stays.
--
-- Same rule as events and the city pages: counts, never names.
-- public_project() returns what, where, how many, what is coming up and
-- what help is wanted. It takes a code, not an id, so nothing can be
-- enumerated, and a project nobody published has no code at all.
--
-- The coach learns two facts (published, has_flyer), so "Promoted" can mean
-- a page or a flyer as well as a published event.
--
-- Idempotent.

-- ---------------------------------------------------------------- the code

alter table public.projects
  add column if not exists share_code text;

create unique index if not exists projects_share_code_key
  on public.projects (share_code)
  where share_code is not null;

comment on column public.projects.share_code is
  'Null until a steward publishes the project. /p/<code> is then public.';

-- Publish (p_code set) or unpublish (p_code null). A project already
-- published keeps the code it has — flyers are already out there. The code
-- is generated by the server action (crypto-random, no look-alike letters)
-- and the unique index above turns a one-in-a-trillion collision into an
-- error the action retries. Stewards only, whatever the projects policies
-- say about editing (they say founders only).
create or replace function public.set_project_sharing(p_id uuid, p_code text)
returns text
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_code text;
begin
  if not coalesce(public.can_steward(p_id, auth.uid()), false) then
    raise exception 'not a steward of this project' using errcode = '42501';
  end if;

  if p_code is null then
    update public.projects set share_code = null where id = p_id;
    return null;
  end if;

  if p_code !~ '^[A-HJ-NP-Z2-9]{8}$' then
    raise exception 'not a share code' using errcode = '22023';
  end if;

  update public.projects
     set share_code = coalesce(share_code, p_code)
   where id = p_id
  returning share_code into v_code;

  return v_code;
end;
$$;

revoke all on function public.set_project_sharing(uuid, text) from public, anon;
grant execute on function public.set_project_sharing(uuid, text) to authenticated;

-- --------------------------------------------------------------- the flyer

create table if not exists public.project_flyers (
  project_id uuid primary key references public.projects (id) on delete cascade,
  headline text not null check (char_length(headline) between 1 and 80),
  subline text not null default '' check (char_length(subline) <= 160),
  body text not null default '' check (char_length(body) <= 600),
  -- Up to three short lines, as a JSON array of strings.
  bullets jsonb not null default '[]'::jsonb
    check (jsonb_typeof(bullets) = 'array' and jsonb_array_length(bullets) <= 3),
  cta text not null default '' check (char_length(cta) <= 120),
  style text not null default 'teal'
    check (style in ('teal', 'sunrise', 'garden', 'ink')),
  -- What the steward told the assistant last time, so it is there next time.
  hint text check (hint is null or char_length(hint) <= 300),
  -- Which model wrote the current draft; null once the steward has edited it
  -- by hand, because then it is theirs.
  model text,
  generated_at timestamptz,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users (id) on delete set null
);

alter table public.project_flyers enable row level security;

-- Stewards read and write their own project's flyer. Nobody else reads the
-- table: the public page gets the copy through public_project() below.
drop policy if exists "stewards read flyer" on public.project_flyers;
create policy "stewards read flyer"
  on public.project_flyers for select to authenticated
  using (public.can_steward(project_id, auth.uid()));

drop policy if exists "stewards write flyer" on public.project_flyers;
create policy "stewards write flyer"
  on public.project_flyers for insert to authenticated
  with check (public.can_steward(project_id, auth.uid()));

drop policy if exists "stewards change flyer" on public.project_flyers;
create policy "stewards change flyer"
  on public.project_flyers for update to authenticated
  using (public.can_steward(project_id, auth.uid()))
  with check (public.can_steward(project_id, auth.uid()));

drop policy if exists "stewards remove flyer" on public.project_flyers;
create policy "stewards remove flyer"
  on public.project_flyers for delete to authenticated
  using (public.can_steward(project_id, auth.uid()));

-- ------------------------------------------------------- the public face

-- The public face of one shared project. Counts, never names.
create or replace function public.public_project(p_code text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    -- The id is here so that "Join" can send someone who signs up straight
    -- to the project inside the app. It unlocks nothing on its own: every
    -- page that takes a project id still requires a session.
    'id', p.id,
    'title', p.title,
    'description', p.description,
    'category', p.category,
    'state', p.state,
    'help', p.help,
    'when_text', p.when_text,
    'photo_url', p.photo_url,
    'photo_credit_name', p.photo_credit_name,
    'photo_credit_url', p.photo_credit_url,
    'created_at', p.created_at,
    'community', (
      select jsonb_build_object('name', n.name, 'city', n.city)
        from public.neighborhoods n where n.id = p.neighborhood_id
    ),
    'stars', (select count(*) from public.stars s where s.project_id = p.id),
    'team', 1 + (select count(*) from public.memberships m
                  where m.project_id = p.id and m.status = 'accepted'),
    'updates', (select count(*) from public.project_updates u where u.project_id = p.id),
    'last_update_at', (select max(u.created_at) from public.project_updates u
                        where u.project_id = p.id),
    -- The next three things on the calendar. Published ones carry their code
    -- so the page can link to them.
    'events', coalesce((
      select jsonb_agg(jsonb_build_object(
        'title', e.title,
        'starts_at', e.starts_at,
        'ends_at', e.ends_at,
        'place', e.place,
        'share_code', e.share_code,
        'going', (select count(*) from public.rsvps r where r.event_id = e.id))
        order by e.starts_at)
        from (
          select * from public.events e
           where e.project_id = p.id
             and e.cancelled_at is null
             and e.starts_at > now() - interval '14 hours'
           order by e.starts_at
           limit 3
        ) e
    ), '[]'::jsonb),
    -- Jobs on upcoming events that still need someone.
    'jobs', coalesce((
      select jsonb_agg(j.title)
        from (
          select ro.title
            from public.event_roles ro
            join public.events e on e.id = ro.event_id
           where e.project_id = p.id
             and e.cancelled_at is null
             and e.starts_at > now() - interval '14 hours'
             and ro.needed > (select count(*) from public.event_role_signups s
                               where s.role_id = ro.id)
           order by e.starts_at, ro.position
           limit 6
        ) j
    ), '[]'::jsonb),
    'flyer', (
      select jsonb_build_object(
        'headline', f.headline, 'subline', f.subline, 'body', f.body,
        'bullets', f.bullets, 'cta', f.cta, 'style', f.style)
        from public.project_flyers f where f.project_id = p.id
    )
  )
    from public.projects p
   where p.share_code = p_code
     and p.state <> 'archived'::project_state;
$$;

revoke all on function public.public_project(text) from public;
grant execute on function public.public_project(text) to anon, authenticated;

-- ---------------------------------------------------------- the studio

-- Everything the flyer studio needs, in one read, for a steward only:
-- anyone else gets null. SECURITY DEFINER so the counts are the whole truth
-- rather than what the caller's own policies let through.
create or replace function public.flyer_page(p_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select case
    when coalesce(public.can_steward(p_id, auth.uid()), false) then
      jsonb_build_object(
        'project', (
          select jsonb_build_object(
            'id', p.id,
            'title', p.title,
            'description', p.description,
            'category', p.category,
            'state', p.state,
            'help', p.help,
            'when_text', p.when_text,
            'photo_url', p.photo_url,
            'share_code', p.share_code,
            'neighborhood', (
              select jsonb_build_object('name', n.name, 'city', n.city)
                from public.neighborhoods n where n.id = p.neighborhood_id
            ))
            from public.projects p where p.id = p_id
        ),
        'stars', (select count(*) from public.stars s where s.project_id = p_id),
        'team', 1 + (select count(*) from public.memberships m
                      where m.project_id = p_id and m.status = 'accepted'),
        'events', coalesce((
          select jsonb_agg(jsonb_build_object(
            'title', e.title, 'starts_at', e.starts_at, 'ends_at', e.ends_at,
            'place', e.place, 'share_code', e.share_code)
            order by e.starts_at)
            from (
              select * from public.events e
               where e.project_id = p_id
                 and e.cancelled_at is null
                 and e.starts_at > now() - interval '14 hours'
               order by e.starts_at
               limit 3
            ) e
        ), '[]'::jsonb),
        'jobs', coalesce((
          select jsonb_agg(j.title)
            from (
              select ro.title
                from public.event_roles ro
                join public.events e on e.id = ro.event_id
               where e.project_id = p_id
                 and e.cancelled_at is null
                 and e.starts_at > now() - interval '14 hours'
                 and ro.needed > (select count(*) from public.event_role_signups s
                                   where s.role_id = ro.id)
               order by e.starts_at, ro.position
               limit 6
            ) j
        ), '[]'::jsonb),
        'flyer', (
          select jsonb_build_object(
            'headline', f.headline, 'subline', f.subline, 'body', f.body,
            'bullets', f.bullets, 'cta', f.cta, 'style', f.style,
            'hint', f.hint, 'model', f.model,
            'generated_at', f.generated_at, 'updated_at', f.updated_at)
            from public.project_flyers f where f.project_id = p_id
        )
      )
    else null
  end;
$$;

revoke all on function public.flyer_page(uuid) from public, anon;
grant execute on function public.flyer_page(uuid) to authenticated;

-- ------------------------------------------------------------- the coach

-- Same as 0080, plus 'published' and 'has_flyer'.
create or replace function public.coach_project_row(p_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id', p.id,
    'title', p.title,
    'state', p.state,
    'created_at', p.created_at,
    'has_photo', p.photo_url is not null,
    'desc_len', char_length(coalesce(p.description, '')),
    'stars', (select count(*) from public.stars s where s.project_id = p.id),
    'stars_7d', (select count(*) from public.stars s
                  where s.project_id = p.id and s.created_at > now() - interval '7 days'),
    'views_7d', (select count(*) from public.project_views v
                  where v.project_id = p.id and v.viewed_on > current_date - 7),
    'views_prev_7d', (select count(*) from public.project_views v
                       where v.project_id = p.id
                         and v.viewed_on > current_date - 14
                         and v.viewed_on <= current_date - 7),
    'team', (select count(*) from public.memberships m
              where m.project_id = p.id and m.status = 'accepted'),
    'pending', (select count(*) from public.memberships m
                 where m.project_id = p.id and m.status = 'pending'),
    -- Help someone logged that is waiting for a steward to accept it.
    'logged', (select count(*) from public.contributions c
                where c.project_id = p.id and c.status = 'logged'),
    'confirmed', (select count(*) from public.contributions c
                   where c.project_id = p.id and c.status = 'confirmed'),
    'updates', (select count(*) from public.project_updates u where u.project_id = p.id),
    -- Quiet since: the last time anything visible happened on it.
    'last_activity_at', greatest(
      p.created_at,
      (select max(u.created_at) from public.project_updates u where u.project_id = p.id),
      (select max(e.created_at) from public.events e where e.project_id = p.id)
    ),
    'events_total', (select count(*) from public.events e where e.project_id = p.id),
    'events_published', (select count(*) from public.events e
                           where e.project_id = p.id and e.share_code is not null),
    -- Promoted another way (0082): a public page, a flyer.
    'published', p.share_code is not null,
    'has_flyer', exists (
      select 1 from public.project_flyers f where f.project_id = p.id
    ),
    'next_event', (
      select jsonb_build_object(
        'id', e.id,
        'title', e.title,
        'starts_at', e.starts_at,
        'published', e.share_code is not null,
        'going', (select count(*) from public.rsvps r where r.event_id = e.id),
        'jobs', (select count(*) from public.event_roles ro where ro.event_id = e.id),
        'open_spots', coalesce((
          select sum(greatest(0, ro.needed - (
                   select count(*) from public.event_role_signups s where s.role_id = ro.id)))
            from public.event_roles ro where ro.event_id = e.id
        ), 0))
        from public.events e
       where e.project_id = p.id
         and e.cancelled_at is null
         and e.starts_at > now() - interval '14 hours'
       order by e.starts_at
       limit 1
    ),
    -- The most recent event that has happened, within the last ten days.
    'last_event', (
      select jsonb_build_object(
        'id', e.id,
        'title', e.title,
        'starts_at', e.starts_at,
        'updates_since', (select count(*) from public.project_updates u
                           where u.project_id = p.id and u.created_at > e.starts_at))
        from public.events e
       where e.project_id = p.id
         and e.cancelled_at is null
         and e.starts_at <= now() - interval '14 hours'
         and e.starts_at > now() - interval '10 days'
       order by e.starts_at desc
       limit 1
    ),
    'has_nudge', exists (
      select 1 from public.project_nudges n
       where n.project_id = p.id and n.dismissed_at is null
    )
  )
    from public.projects p
   where p.id = p_id;
$$;

revoke all on function public.coach_project_row(uuid) from public, anon, authenticated;
