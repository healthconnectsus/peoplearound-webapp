#!/usr/bin/env node
/**
 * gen-demo-avatars.mjs — a face for every demo neighbor.
 *
 * Usage: node scripts/gen-demo-avatars.mjs
 *
 * The demo accounts (u1…u100) had no avatar, so every seeded feed card fell
 * back to initials on a green circle and the place looked like a spreadsheet.
 * This draws each of them a small flat-illustration portrait as an SVG:
 * background, skin tone, hair colour and style, shirt colour — picked
 * deterministically from the account number, so u7 always looks like u7 and
 * re-running this changes nothing.
 *
 * Deliberately *drawn*, not photographic. Photos of real people can't be
 * used as the faces of fictional residents — the people in them never
 * agreed to live in Aurora — and an illustrated avatar also reads honestly
 * as "this is a demo neighbor" instead of quietly implying a real one.
 *
 * Output: public/avatars/demo/uNN.svg, and a SQL file that points each demo
 * profile at its own.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(root, "public/avatars/demo");
const COUNT = 100;

// Palettes chosen to sit calmly next to the app's emerald without all
// looking like the same person in different lighting.
const BACKGROUNDS = [
  "#d1fae5", "#dbeafe", "#fef3c7", "#fce7f3",
  "#e0e7ff", "#ccfbf1", "#ffedd5", "#f3e8ff",
];
const SKIN = ["#8d5524", "#c68642", "#e0ac69", "#f1c27d", "#ffdbac", "#5c3317"];
const HAIR = ["#1f2937", "#4b2e1e", "#8b4513", "#b45309", "#d1d5db", "#7c3aed"];
const SHIRT = ["#0f766e", "#b91c1c", "#1d4ed8", "#7c3aed", "#c2410c", "#334155"];

/**
 * Hair shapes, drawn over the head. Index picks one. Every path is tuned to
 * a head spanning x 17–47, y 9–43 — change the head and these must follow.
 */
function hair(style, color) {
  switch (style) {
    case 0: // short crop
      return `<path d="M17 26c0-10 6-17 15-17s15 7 15 17c0 0-4-7-15-7s-15 7-15 7z" fill="${color}"/>`;
    case 1: // bun
      return `<path d="M17 27c0-11 6-18 15-18s15 7 15 18c0 0-4-8-15-8s-15 8-15 8z" fill="${color}"/><circle cx="32" cy="6" r="5.5" fill="${color}"/>`;
    case 2: // long
      return `<path d="M16 27c0-11 7-18 16-18s16 7 16 18v17c0 2-2 3-4 2V25c0-4-5-7-12-7s-12 3-12 7v21c-2 1-4 0-4-2V27z" fill="${color}"/>`;
    case 3: // curly
      return `<g fill="${color}"><circle cx="20" cy="21" r="8"/><circle cx="32" cy="14" r="9"/><circle cx="44" cy="21" r="8"/><circle cx="26" cy="15" r="8"/><circle cx="38" cy="15" r="8"/></g>`;
    case 4: // side part
      return `<path d="M17 27c0-10 6-18 15-18 7 0 12 4 14 10-7-4-18-3-23 1-3 3-5 9-5 9s-1-1-1-2z" fill="${color}"/>`;
    default: // headscarf / cap
      return `<path d="M16 27c0-11 7-18 16-18s16 7 16 18c0 2-2 3-3 2-3-5-8-7-13-7s-10 2-13 7c-1 1-3 0-3-2z" fill="${color}"/>`;
  }
}

/**
 * Knuth multiplicative hash, one independent stream per feature. Picking
 * with `(i * step) % len` instead made the traits move in lockstep — every
 * sixth neighbor wore the same shirt, and a grid of them rhymed in columns.
 */
function hash(i, salt) {
  return Math.imul(i + salt * 0x9e37, 2654435761) >>> 8;
}
const pick = (arr, i, salt) => arr[hash(i, salt) % arr.length];

function avatar(i) {
  const bg = pick(BACKGROUNDS, i, 1);
  const skin = pick(SKIN, i, 2);
  const hairColor = pick(HAIR, i, 3);
  const style = hash(i, 4) % 6;
  const shirt = pick(SHIRT, i, 5);
  const beard = hash(i, 6) % 4 === 0;

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="Demo neighbor avatar">
  <defs><clipPath id="c"><circle cx="32" cy="32" r="32"/></clipPath></defs>
  <g clip-path="url(#c)">
    <rect width="64" height="64" fill="${bg}"/>
    <path d="M32 44c12 0 22 9 22 20v4H10v-4c0-11 10-20 22-20z" fill="${shirt}"/>
    <rect x="27" y="37" width="10" height="10" rx="4" fill="${skin}"/>
    <ellipse cx="32" cy="26" rx="15" ry="17" fill="${skin}"/>
    ${beard ? `<path d="M19 28c0 11 6 17 13 17s13-6 13-17c2 9 0 21-13 21s-15-12-13-21z" fill="${hairColor}" opacity=".8"/>` : ""}
    ${hair(style, hairColor)}
    <circle cx="26.5" cy="26" r="2" fill="#1f2937"/>
    <circle cx="37.5" cy="26" r="2" fill="#1f2937"/>
    <path d="M27 33c1.8 2.2 8.2 2.2 10 0" stroke="#1f2937" stroke-width="1.8" stroke-linecap="round" fill="none"/>
  </g>
</svg>`;
}

mkdirSync(outDir, { recursive: true });
const values = [];
for (let i = 1; i <= COUNT; i++) {
  writeFileSync(resolve(outDir, `u${i}.svg`), avatar(i), "utf8");
  values.push(`('u${i}@example.com', '/avatars/demo/u${i}.svg')`);
}

const sql = `-- Generated by scripts/gen-demo-avatars.mjs — do not hand-edit.
-- Points every demo account at its drawn portrait. Idempotent.
update public.profiles p
   set avatar_url = v.url
  from (values
    ${values.join(",\n    ")}
  ) as v(email, url)
  join auth.users u on u.email = v.email
 where p.id = u.id
   and p.avatar_url is distinct from v.url;
`;
writeFileSync(resolve(root, "supabase/demo-avatars.sql"), sql, "utf8");

console.log(`✅ ${COUNT} avatars → public/avatars/demo/`);
console.log("✅ supabase/demo-avatars.sql — apply with scripts/db-apply.mjs");
